local suffixes = {
    [" (Root Dir)"] = "（项目根目录）",
    [" (cwd)"] = "（当前工作目录）",
    [" (Trouble)"] = "（Trouble）",
}

-- 已由本地持久开关接管，但上游仍可能提供动态的 Enable/Disable 菜单文案。
local toggle_names = {
    Diagnostics = "诊断",
    Spelling = "拼写检查",
    ["Relative Number"] = "相对行号",
    ["Conceal Level"] = "文本隐藏",
    ["Inlay Hints"] = "行内提示",
    ["Auto Format (Global)"] = "全局自动格式化",
}

---@param description string
---@return string
return function(description)
    local translated = descriptions[description]
    if translated then
        return translated
    end
    local action, name = description:match("^(%a+) (.+)$")
    if action == "Enable" or action == "Disable" then
        local label = toggle_names[name] or descriptions["Toggle " .. name]
        if label then
            return (action == "Enable" and "开启" or "关闭")
                .. label:gsub("^切换", "")
        end
    end
    -- 仅合并明确的作用范围后缀，不逐词替换，避免改变技术名词和句意。
    for suffix, label in pairs(suffixes) do
        if vim.endswith(description, suffix) then
            local base = description:sub(1, -#suffix - 1)
            if descriptions[base] then
                return descriptions[base] .. label
            end
        end
    end
    return description
end
